namespace Strathweb.A2UI.Surfaces;

/// <summary>The role an image plays in a layout, which decides how large it is drawn.</summary>
public enum ImageVariant
{
    /// <summary>The <c>icon</c> value.</summary>
    Icon = 1,

    /// <summary>The <c>avatar</c> value.</summary>
    Avatar = 2,

    /// <summary>The <c>smallFeature</c> value.</summary>
    SmallFeature = 3,

    /// <summary>The <c>mediumFeature</c> value.</summary>
    MediumFeature = 4,

    /// <summary>The <c>largeFeature</c> value.</summary>
    LargeFeature = 5,

    /// <summary>The <c>header</c> value.</summary>
    Header = 6,
}
