public enum ImageFit
{
    /// <summary>The <c>contain</c> value.</summary>
    Contain = 1,

    /// <summary>The <c>cover</c> value.</summary>
    Cover = 2,

    /// <summary>The <c>fill</c> value.</summary>
    Fill = 3,

    /// <summary>The <c>none</c> value.</summary>
    None = 4,

    /// <summary>The <c>scaleDown</c> value.</summary>
    ScaleDown = 5,
}
